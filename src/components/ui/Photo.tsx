import { preload } from "react-dom";
import manifest from "@/content/images.generated.json";
import { cn } from "@/lib/utils";

// Ids come from assets/images.json after `npm run images`.
export type PhotoId = keyof typeof manifest;

type PhotoProps = {
  id: PhotoId;
  alt: string;
  /** Same meaning as the HTML `sizes` attribute, e.g. "(min-width: 1024px) 33vw, 100vw". */
  sizes?: string;
  /** Use for the one image that is the largest thing on screen at load (LCP). */
  priority?: boolean;
  /** Load right away without the high-priority hint (for images that mount just before they are needed). */
  eager?: boolean;
  imgStyle?: React.CSSProperties;
  className?: string;
  imgClassName?: string;
};

export function Photo({
  id,
  alt,
  sizes = "100vw",
  priority = false,
  eager = false,
  className,
  imgClassName,
  imgStyle,
}: PhotoProps) {
  const m = manifest[id];
  const srcSet = (ext: "avif" | "webp") =>
    m.widths.map((w) => `/images/${id}-${w}.${ext} ${w}w`).join(", ");
  const fallback = m.widths.includes(1280) ? 1280 : Math.max(...m.widths);

  // Tell the browser to start downloading the LCP image before it reaches the <img> tag.
  if (priority) {
    preload(`/images/${id}-${fallback}.avif`, {
      as: "image",
      type: "image/avif",
      imageSrcSet: srcSet("avif"),
      imageSizes: sizes,
      fetchPriority: "high",
    });
  }

  return (
    <picture className={cn("block overflow-hidden", className)}>
      <source type="image/avif" srcSet={srcSet("avif")} sizes={sizes} />
      <source type="image/webp" srcSet={srcSet("webp")} sizes={sizes} />
      {/* Plain <img> on purpose: files are pre-generated by scripts/process-images.mjs. */}
      <img
        src={`/images/${id}-${fallback}.webp`}
        alt={alt}
        width={m.width}
        height={m.height}
        sizes={sizes}
        loading={priority || eager ? "eager" : "lazy"}
        fetchPriority={priority ? "high" : "auto"}
        decoding="async"
        style={{ backgroundImage: `url(${m.blur})`, backgroundSize: "cover", ...imgStyle }}
        className={cn("h-full w-full object-cover", imgClassName)}
      />
    </picture>
  );
}
