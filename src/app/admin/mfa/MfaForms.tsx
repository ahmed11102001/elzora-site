"use client";

import { useActionState, useState, useTransition } from "react";
import {
  startEnrollment,
  verifyCode,
  type EnrollState,
  type FormState,
} from "@/admin/auth/actions";
import { buttonClass, TextField } from "@/admin/ui/primitives";

function CodeForm({ factorId, submitLabel }: { factorId?: string; submitLabel: string }) {
  const [state, action, pending] = useActionState<FormState, FormData>(verifyCode, {});
  return (
    <form action={action} className="grid gap-4" noValidate>
      {factorId && <input type="hidden" name="factorId" value={factorId} />}
      <TextField
        id="code"
        name="code"
        label="6-digit code"
        inputMode="numeric"
        autoComplete="one-time-code"
        maxLength={6}
        pattern="[0-9]{6}"
        required
        error={state.error}
      />
      <button type="submit" disabled={pending} aria-busy={pending} className={buttonClass()}>
        {pending ? "Checking…" : submitLabel}
      </button>
    </form>
  );
}

/** Existing account: ask for the current code. */
export function VerifyForm() {
  return <CodeForm submitLabel="Verify" />;
}

/** First sign-in: show the QR code, then confirm with a code. */
export function EnrollFlow() {
  const [enroll, setEnroll] = useState<EnrollState | null>(null);
  const [pending, start] = useTransition();

  if (!enroll?.factorId) {
    return (
      <div className="grid gap-4">
        <p className="text-sm text-ink/75">
          Two-step verification is required. You will need an authenticator app (Google
          Authenticator, Microsoft Authenticator, 1Password or similar).
        </p>
        {enroll?.error && (
          <p role="alert" className="rounded-lg bg-red-50 px-4 py-3 text-sm text-red-800">
            {enroll.error}
          </p>
        )}
        <button
          type="button"
          disabled={pending}
          aria-busy={pending}
          className={buttonClass()}
          onClick={() => start(async () => setEnroll(await startEnrollment()))}
        >
          {pending ? "Preparing…" : "Set up authenticator app"}
        </button>
      </div>
    );
  }

  return (
    <div className="grid gap-5">
      <ol className="list-decimal space-y-1 pl-5 text-sm text-ink/75">
        <li>Scan this QR code with your authenticator app.</li>
        <li>Enter the 6-digit code the app shows.</li>
      </ol>
      {enroll.qr && (
        // The QR code is a data URI generated by Supabase; there is nothing to optimise.
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={enroll.qr}
          alt="QR code for the authenticator app"
          className="mx-auto size-48 rounded-lg border border-ink/10"
        />
      )}
      {enroll.secret && (
        <p className="text-center text-xs text-ink/65">
          Cannot scan? Enter this key manually:
          <br />
          <code className="mt-1 inline-block rounded bg-ink/5 px-2 py-1 text-sm tracking-wider select-all">
            {enroll.secret}
          </code>
        </p>
      )}
      <CodeForm factorId={enroll.factorId} submitLabel="Confirm and continue" />
    </div>
  );
}
